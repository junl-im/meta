const {app,BrowserWindow,session}=require('electron')
const assert=require('node:assert/strict')
const {existsSync,mkdirSync,readFileSync,unlinkSync}=require('node:fs')
const {join}=require('node:path')
const output=join(process.cwd(),'.test-tmp','web-smoke.wtoon')
const pngOutput=join(process.cwd(),'.test-tmp','web-smoke-png.zip')
const wait=async(check)=>{for(let i=0;i<100;i++){if(await check())return;await new Promise(resolve=>setTimeout(resolve,100))}throw Error('웹 화면이 응답하지 않습니다.')}
app.whenReady().then(async()=>{
  try{
    mkdirSync(join(process.cwd(),'.test-tmp'),{recursive:true})
    if(existsSync(output))unlinkSync(output)
    if(existsSync(pngOutput))unlinkSync(pngOutput)
    const win=new BrowserWindow({width:1280,height:800,show:false,webPreferences:{sandbox:true,contextIsolation:true}})
    const errors=[];win.webContents.on('console-message',(_,level,message)=>{if(level>=3)errors.push(message)})
    session.defaultSession.on('will-download',(_,item)=>item.setSavePath(item.getFilename().endsWith('.zip')?pngOutput:output))
    await win.loadURL('http://127.0.0.1:45173/')
    const js=source=>win.webContents.executeJavaScript(source)
    await wait(()=>js(`!!document.querySelector('.web-app')`))
    await js(`Array.from(document.querySelectorAll('.web-actions button')).find(b=>b.textContent.includes('컷')).click()`)
    assert.equal(await js(`document.querySelectorAll('.web-panel').length`),1)
    await js(`Array.from(document.querySelectorAll('.web-actions button')).find(b=>b.textContent.includes('말풍선')).click()`)
    assert.equal(await js(`document.querySelectorAll('.web-bubble').length`),1)
    await js(`document.querySelector('.web-section textarea').value='웹 저장 검사';document.querySelector('.web-section textarea').dispatchEvent(new Event('input',{bubbles:true}))`)
    await js(`Array.from(document.querySelectorAll('.web-top-actions button')).find(b=>b.textContent.includes('.wtoon 저장')).click()`)
    await wait(()=>Promise.resolve(existsSync(output)))
    const {decodeWtoon}=await import('../dist-main/main/wtoonPackage.js')
    const saved=decodeWtoon(new Uint8Array(readFileSync(output)))
    assert.equal(saved.elements.filter(e=>e.type==='panel').length,1)
    assert.equal(saved.elements.filter(e=>e.type==='bubble').length,1)
    await js(`Array.from(document.querySelectorAll('.web-toolbar button')).find(b=>b.textContent.includes('PNG 초안')).click()`)
    await wait(()=>Promise.resolve(existsSync(pngOutput)))
    const {unzipSync}=require('fflate'),pages=unzipSync(new Uint8Array(readFileSync(pngOutput)))
    assert(Object.keys(pages).length>=3)
    assert(Object.keys(pages).every(name=>name.endsWith('.png')))
    assert.deepEqual(errors,[])
    console.log('WEB_BROWSER_EDIT_WTOON_DESKTOP_ROUNDTRIP_PNG=PASS')
    const mobile=new BrowserWindow({width:390,height:844,show:false,webPreferences:{sandbox:true,contextIsolation:true}})
    await mobile.loadURL('http://127.0.0.1:45173/')
    const mobileJs=source=>mobile.webContents.executeJavaScript(source)
    await wait(()=>mobileJs(`!!document.querySelector('.web-mobile-nav')`))
    assert.equal(await mobileJs(`getComputedStyle(document.querySelector('.web-mobile-nav')).display`),'grid')
    await mobileJs(`Array.from(document.querySelectorAll('.web-mobile-nav button')).find(b=>b.textContent==='도구').click()`)
    assert.notEqual(await mobileJs(`getComputedStyle(document.querySelector('.web-side:not(.web-right)')).display`),'none')
    await mobileJs(`Array.from(document.querySelectorAll('.web-mobile-nav button')).find(b=>b.textContent.startsWith('레이어')).click()`)
    assert.notEqual(await mobileJs(`getComputedStyle(document.querySelector('.web-right')).display`),'none')
    await mobileJs(`Array.from(document.querySelectorAll('.web-mobile-nav button')).find(b=>b.textContent==='캔버스').click()`)
    assert.notEqual(await mobileJs(`getComputedStyle(document.querySelector('.web-center')).display`),'none')
    console.log('WEB_MOBILE_TOOLS_CANVAS_PROPERTIES=PASS')
    await mobile.close()
    await win.close();app.exit(0)
  }catch(error){console.error(error);app.exit(1)}
})
